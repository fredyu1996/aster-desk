# Builds the desk (index.html) and the cloud trader's code (bot/core.js) from src/.
#   npm install        (once: three.js for the desk)
#   python3 build.py
import json, os
ROOT = os.path.dirname(os.path.abspath(__file__))
P = lambda *a: os.path.join(ROOT, *a)
h = open(P('src', 'head.html')).read()
three = open(P('node_modules', 'three', 'build', 'three.min.js')).read()
unl = json.dumps(json.load(open(P('unlocks.json'))), separators=(',', ':'))   # snapshot embedded so the desk works as a local file
unlock_js = open(P('src', 'unlock.js')).read().replace('/*UNLOCKS_JSON*/null', unl)
src = lambda f: unlock_js if f == 'unlock.js' else open(P('src', f)).read()
order = ['engine.js', 'track.js', 'unlock.js', 'trader.js', 'smc.js', 'scene.js', 'ui.js', 'check.js', 'trader_ui.js', 'review.js', 'smc_ui.js', 'lessons.js', 'sync.js']
app = '\n'.join(src(f) for f in order)
assert '</script' not in app.lower()
h = h.replace('/*THREE_INLINE*/', three).replace('/*APP_JS*/', app)
open(P('index.html'), 'w').write(h)
print('built index.html', len(h) // 1024, 'KB')

# ---- cloud bot core: the desk's own trading logic, without the 3D scene / panels ----
rv = open(P('src', 'review.js')).read()
rv = rv[:rv.index('/* ================= REVIEWER: screens + panel')]
core = ('// GENERATED by build.py from the desk source (engine, tracker, unlocks, Trader, Reviewer). Do not edit by hand.\n'
        + '\n'.join(src(f) for f in ['engine.js', 'track.js', 'unlock.js', 'trader.js', 'smc.js']) + '\n' + rv)
open(P('bot', 'core.js'), 'w').write(core)
print('built bot/core.js', len(core) // 1024, 'KB')
