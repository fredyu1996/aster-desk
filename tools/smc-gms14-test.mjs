// live rule, writes no shared file). Switches: comment above smNc and smL5Find in src/smc.js. Every variant sets SM.cfg.X AND
// SB_OV.X (SMC Big / BTC-ETH take SM.cfg + SB_OV, so SM.cfg alone would not reach them).
// Same windows as tools/smc-fib-test.mjs: GT_PART=week = small caps + big caps over GT_DAYS (default 21); GT_PART=year = SMC Big settings
// (= SMC BTC/ETH) on BTC + ETH over 365 d. GT_END pins the window end (ms); GT_CACHE=<file> keeps the candles (same format as
// tools/smc-ind-study.mjs); GT_OLD=<dir with a pre-change backtest.mjs + core.js> adds "base-old" (switches at 0 must reproduce it
// trade for trade); GT_ONLY=base,ltf5m limits the variants; GT_ACCT=small,big limits the week accounts.
// This tool runs its own copy of bot/backtest.mjs simulate() that also hands the core the closed 5m bars (S.k5) ltf5m needs.
// Usage (after build.py): GT_PART=week node tools/smc-gms14-test.mjs <state.json> <out.json>
//        GT_PART=report node tools/smc-gms14-test.mjs <out1.json,out2.json,...> <report.md>
