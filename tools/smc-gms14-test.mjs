const stats = A => {
  const R = A.map(x => x.R), tot = R.reduce((a, b) => a + b, 0); let eq = 0, pk = 0, dd = 0;
  for (const x of [...A].sort((a, b) => a.t1 - b.t1)) { eq += x.R; pk = Math.max(pk, eq); dd = Math.max(dd, pk - eq); }
  return {n: R.length, win: R.length ? Math.round(R.filter(v => v > 0).length / R.length * 100) : null, totR: +tot.toFixed(2), avgR: R.length ? +(tot / R.length).toFixed(3) : null, ddR: +dd.toFixed(2)};
};
const f = s => s.n ? `n ${String(s.n).padStart(3)} win ${String(s.win).padStart(3)}% avg ${s.avgR >= 0 ? '+' : ''}${s.avgR.toFixed(2)}R tot ${String(s.totR).padStart(6)}R dd ${s.ddR}R` : 'n   0';

