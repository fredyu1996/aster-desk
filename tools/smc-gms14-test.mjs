// bot/backtest.mjs simulate(), unchanged except: S.k5 gets each coin's last 150 closed 5m bars, and the 5m checks are counted (__L5)
async function sim5(name, D, U, steps, setup, big) {
  const A = big ? 'SB' : 'SM', W = c => big ? `smWith(SB, () => (${c}))` : c;
  const {ctx, X} = await mkCore(st.cfg, exInfo);
  ctx.__ST = {cfg: (st.sm && st.sm.cfg) || {}, adj: (st.rv && st.rv.smAdj) || {}};
  X(`${PREP}
     var __walk = (s, o, h, l, c, tEnd) => { const p = SM.pos[s]; if (!p) return; CLOCK_OVR = tEnd; const L = p.side === 'L'; let prev = o;
       for (const v of L ? [o, l, h, c] : [o, h, l, c]) { const q = SM.pos[s]; if (!q) break; const d = Math.abs(q.entry - q.stop0), dir = L ? 1 : -1;
         const lv = [q.stop, q.tp1 ? null : q.entry + dir * (q.tp1R || SM.cfg.tp1R) * d, q.target].filter(z => z != null && isFinite(z));
         const pts = lv.filter(z => (z - prev) * (z - v) <= 0 && z !== prev).sort((a, b) => Math.abs(a - prev) - Math.abs(b - prev));
         for (const z of [...pts, v]) { if (!SM.pos[s]) break; PX_OVR = {[s]: z}; smManage(CLOCK_OVR, s); } prev = v; }
       PX_OVR = null; CLOCK_OVR = 0; };
     var __L5 = {}, __l5o = smL5Tick, __l5s = smL5Start;
     smL5Start = c => { __L5.started = (__L5.started || 0) + 1; return __l5s(c); };
     smL5Tick = t => { const B = [...S.l5.values()]; __l5o(t); for (const P of B) if (S.l5.get(smKey() + '|' + P.s) !== P) { const w = (P.why || 'filled').replace(/-?\\d+\\.\\d+/g, '#'); __L5[w] = (__L5[w] || 0) + 1; } };`);
  if (big) X(`SB = JSON.parse(JSON.stringify(SB_DEF)); SB.created = 0;`);
  if (setup) X(setup);
  const trades = [];
  for (const T of steps) {
    for (const s of X(`Object.keys(${A}.pos)`)) { const C = D[s], i = C ? nClosed(C.m5, M5, T) - 1 : -1; if (i >= 0 && C.m5[i][0] === T - M5) { const b = C.m5[i]; ctx.__B = [s, b[1], b[2], b[3], b[4], T - 1]; X(W('__walk(...__B)')); } }
    const u = U.get(Math.floor(T / H) * H); if (!u) continue;
    const F = {};
    for (const s of new Set([...(big ? u.big : Object.keys(u.trk)), ...X(`Object.keys(${A}.pos)`)])) {
      const v = D[s] && viewAt(D[s], T); if (!v) continue; const t24 = u.tk[s], n5 = nClosed(D[s].m5, M5, T);
      F[s] = {k: v.k, h: v.h, m5: D[s].m5.slice(Math.max(0, n5 - 150), n5), tk: {last: v.last, pct: t24 ? (v.last / (t24.last / (1 + t24.pct / 100)) - 1) * 100 : 0, qv: t24 ? t24.qv : 0}};
    }
    ctx.__T = T; ctx.__F = F; ctx.__TRK = u.trk;
    const r = X(W(`(() => { CLOCK_OVR = __T; S.trk = __TRK; S.kl.clear(); S.h1.clear(); S.tk.clear(); S.M.clear(); S.smC.clear(); S.smCB.clear(); S.k5.clear(); S.alerts.length = 0;
      for (const [s, f] of Object.entries(__F)) { S.kl.set(s, {t: __T, bars: f.k}); S.h1.set(s, {t: __T, bars: f.h}); S.tk.set(s, f.tk); S.k5.set(s, {t: __T, bars: f.m5}); }
      smTick(); CLOCK_OVR = 0; return SM.log.splice(0); })()`));
    trades.push(...r);
  }
  return {name, trades: trades.sort((a, b) => a.t0 - b.t0), open: X(`Object.keys(${A}.pos).length`), l5: JSON.parse(X('JSON.stringify(__L5)'))};
}
async function cfgCheck() {
  const {ctx, X} = await mkCore(st.cfg, exInfo); ctx.__ST = {cfg: (st.sm && st.sm.cfg) || {}, adj: (st.rv && st.rv.smAdj) || {}};
  const pick = 'c => ({closedOnly: c.closedOnly, retestExp: c.retestExp, ltf5m: c.ltf5m, gmsB: c.gmsB, gmsC: c.gmsC, gmsD: c.gmsD, fib: c.fib})';
  for (const [k, setup] of V) { if (only && !only.includes(k)) continue; X(PREP); X(setup); out.cfg[k] = JSON.parse(X(`JSON.stringify({small: (${pick})(SM.cfg), big: smWith(SB, () => (${pick})(SM.cfg)), se: smWith(SE, () => (${pick})(SM.cfg))})`)); log(`cfg ${k}: ${JSON.stringify(out.cfg[k])}`); }
}
async function runAll(tag, D, U, steps, isBig, split) {
  for (const [k, setup] of [...V, ...(old ? [['base-old', '']] : [])]) {
    if (only && !only.includes(k)) continue;
    const t1 = Date.now(), r = k === 'base-old' ? await old.simulate(k, st, exInfo, D, U, steps, '', new Map(), isBig) : await sim5(k, D, U, steps, setup, isBig);
    const A = r.trades.filter(x => x.t1 < split), B = r.trades.filter(x => x.t1 >= split);
    out.runs[`${tag}-${k}`] = {all: stats(r.trades), a: stats(A), b: stats(B), open: r.open, l5: r.l5, rows: r.trades.map(x => row(x, k))};
    log(`${tag.padEnd(5)} ${k.padEnd(10)}: ${f(stats(r.trades))} | half 1 ${f(stats(A))} | half 2 ${f(stats(B))}${r.l5 && r.l5.started ? ' | 5m ' + JSON.stringify(r.l5) : ''} (${((Date.now() - t1) / 1e3).toFixed(0)} s)`);
    fs.writeFileSync(OUT, JSON.stringify(out));
  }
  const b = out.runs[`${tag}-base`], o = out.runs[`${tag}-base-old`];
  if (b && o) { const key = x => [x.s, x.side, x.t0, x.t1, x.R].join('|'), same = b.rows.length === o.rows.length && b.rows.every((x, i) => key(x) === key(o.rows[i]));
    b.sameAsOld = same; log(`${tag}: base (switches 0) vs pre-change base, trade for trade: ${same ? 'IDENTICAL' : 'DIFFERENT'}`); fs.writeFileSync(OUT, JSON.stringify(out)); }
}
